import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { LANG_CODES, type LangCode } from "../../src/config/languages";
import type { Story, StoryStatus } from "../../src/lib/types";
import { validateStory } from "../../src/lib/validate";

export const STORIES_DIR = path.join("src", "stories");

/** Stories are read from disk on every call, so edits show up without restarting the worker. */
export const listStoryIds = () =>
  readdirSync(STORIES_DIR)
    .filter((f) => f.endsWith(".json"))
    .map((f) => f.replace(/\.json$/, ""))
    .sort();

export const storyPath = (id: string) => path.join(STORIES_DIR, `${id}.json`);

export const readStory = (id: string): Story => {
  if (!/^[a-z0-9-]+$/.test(id) || !existsSync(storyPath(id))) throw new HttpError(404, `story "${id}" not found`);
  return JSON.parse(readFileSync(storyPath(id), "utf8")) as Story;
};

export const audioManifestPath = (id: string, lang: LangCode) => path.join("public", "audio", id, lang, "manifest.json");

export const voiceLanguages = (id: string) => LANG_CODES.filter((l) => existsSync(audioManifestPath(id, l)));

export const storySummary = (id: string) => {
  const s = readStory(id);
  return {
    id: s.id,
    status: s.status ?? "draft",
    title: s.title,
    scenes: s.scenes.length,
    lines: s.scenes.reduce((n, sc) => n + sc.lines.length, 0),
    voice: voiceLanguages(id),
    assetRequests: s.assetRequests ?? [],
  };
};

/** Keep src/stories/index.ts in sync with the JSON files in the folder. */
export const regenerateIndex = () => {
  const ids = listStoryIds();
  const name = (i: number) => `story${i}`;
  const src = [
    "// Generated by the Studio Worker from the JSON files in this folder. Safe to edit by hand too.",
    'import type { Story } from "../lib/types";',
    ...ids.map((id, i) => `import ${name(i)} from "./${id}.json";`),
    "",
    "/** Every story in src/stories. One JSON file per story. */",
    `export const STORIES: Story[] = [${ids.map((_, i) => `${name(i)} as Story`).join(", ")}];`,
    "",
    "export const getStory = (id: string): Story => {",
    "  const story = STORIES.find((s) => s.id === id);",
    "  if (!story) throw new Error(`Unknown story: ${id}`);",
    "  return story;",
    "};",
    "",
  ].join("\n");
  writeFileSync(path.join(STORIES_DIR, "index.ts"), src);
};

export const writeStory = (story: Story) => {
  const { errors } = validateStory(story);
  if (errors.length) throw new HttpError(422, `story is not valid: ${errors.join("; ")}`);
  writeFileSync(storyPath(story.id), JSON.stringify(story, null, 2) + "\n");
  regenerateIndex();
};

export const setStatus = (id: string, status: StoryStatus) => {
  const story = readStory(id);
  story.status = status;
  writeFileSync(storyPath(id), JSON.stringify(story, null, 2) + "\n");
  return story;
};

export class HttpError extends Error {
  constructor(
    public status: number,
    message: string,
  ) {
    super(message);
  }
}
