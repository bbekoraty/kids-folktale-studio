"""
Original background music + sound effects for Fufu Tales, synthesised from scratch.
No samples, no third-party recordings: everything here is generated by this code,
so the channel owns it outright (no licence or Content ID problems).

Instruments are loose imitations of a Thai ensemble:
  ranat (wooden xylophone), khong (gong circle bells), khim (hammered dulcimer),
  ching (small finger cymbals), thon (hand drum), plus a soft pad and bass.
Melodies use a pentatonic scale, close to the Thai sound.

    python3 scripts/music/generate.py            # writes public/music/*.mp3 and public/sfx/*.mp3

Requires numpy, scipy and ffmpeg.
"""

from __future__ import annotations

import os
import subprocess
import tempfile

import numpy as np
from scipy.io import wavfile
from scipy.signal import butter, fftconvolve, sosfilt

SR = 44100
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


# ───────────────────────── helpers ─────────────────────────

def t_axis(seconds: float) -> np.ndarray:
    return np.arange(int(seconds * SR)) / SR


def midi(n: float) -> float:
    return 440.0 * 2 ** ((n - 69) / 12)


def env_perc(n: int, attack: float, decay: float) -> np.ndarray:
    t = np.arange(n) / SR
    a = np.clip(t / max(attack, 1e-4), 0, 1)
    return a * np.exp(-t / decay)


def lowpass(x: np.ndarray, hz: float, order: int = 2) -> np.ndarray:
    return sosfilt(butter(order, hz, "low", fs=SR, output="sos"), x)


def highpass(x: np.ndarray, hz: float, order: int = 2) -> np.ndarray:
    return sosfilt(butter(order, hz, "high", fs=SR, output="sos"), x)


def bandpass(x: np.ndarray, lo: float, hi: float, order: int = 2) -> np.ndarray:
    return sosfilt(butter(order, [lo, hi], "band", fs=SR, output="sos"), x)


def reverb(x: np.ndarray, seconds: float = 1.6, mix: float = 0.25, seed: int = 1) -> np.ndarray:
    rng = np.random.default_rng(seed)
    n = int(seconds * SR)
    ir = rng.standard_normal(n) * np.exp(-np.arange(n) / (SR * seconds / 5))
    ir = lowpass(ir, 6000)
    ir /= np.sqrt(np.sum(ir**2))
    wet = fftconvolve(x, ir)[: len(x)]
    return x * (1 - mix) + wet * mix


# ───────────────────────── instruments ─────────────────────────

def ranat(freq: float, dur: float = 0.6, vel: float = 1.0, seed: int = 0) -> np.ndarray:
    """Wooden xylophone: inharmonic bar partials, quick decay, soft mallet click."""
    n = int(dur * SR)
    t = np.arange(n) / SR
    tone = (
        np.sin(2 * np.pi * freq * t) * env_perc(n, 0.002, 0.22)
        + 0.35 * np.sin(2 * np.pi * freq * 3.93 * t) * env_perc(n, 0.001, 0.05)
        + 0.12 * np.sin(2 * np.pi * freq * 9.0 * t) * env_perc(n, 0.001, 0.02)
    )
    rng = np.random.default_rng(seed)
    click = bandpass(rng.standard_normal(n), 1500, 5000) * env_perc(n, 0.0005, 0.004) * 0.25
    return (tone + click) * vel


def khong(freq: float, dur: float = 2.2, vel: float = 1.0) -> np.ndarray:
    """Small tuned gong / bell: long ringing, slightly detuned partials."""
    n = int(dur * SR)
    t = np.arange(n) / SR
    out = np.zeros(n)
    for ratio, amp, dec in ((1.0, 1.0, 1.1), (2.01, 0.45, 0.7), (2.76, 0.25, 0.45), (5.4, 0.1, 0.18)):
        out += amp * np.sin(2 * np.pi * freq * ratio * t) * env_perc(n, 0.003, dec)
    return out * vel * 0.6


def khim(freq: float, dur: float = 1.4, vel: float = 1.0, seed: int = 0) -> np.ndarray:
    """Hammered dulcimer via Karplus–Strong plucked string."""
    n = int(dur * SR)
    period = max(2, int(SR / freq))
    rng = np.random.default_rng(seed)
    buf = rng.uniform(-1, 1, period)
    out = np.zeros(n)
    for i in range(n):
        out[i] = buf[i % period]
        buf[i % period] = 0.5 * (buf[i % period] + buf[(i + 1) % period]) * 0.996
    return lowpass(out, 5000) * vel * 0.7


def bass(freq: float, dur: float = 0.9, vel: float = 1.0) -> np.ndarray:
    n = int(dur * SR)
    t = np.arange(n) / SR
    tone = np.sin(2 * np.pi * freq * t) + 0.25 * np.sin(2 * np.pi * 2 * freq * t)
    return tone * env_perc(n, 0.01, 0.35) * vel * 0.5


def pad(freqs: list[float], dur: float, vel: float = 1.0) -> np.ndarray:
    """Soft warm pad: detuned saws, low-passed, slow swell."""
    n = int(dur * SR)
    t = np.arange(n) / SR
    out = np.zeros(n)
    for f in freqs:
        for det in (-0.004, 0.0, 0.005):
            ph = (f * (1 + det) * t) % 1.0
            out += 2 * ph - 1
    out = lowpass(out, 1400, 2)
    swell = np.minimum(1, t / 1.2) * np.minimum(1, (dur - t) / 1.2)
    return out * np.clip(swell, 0, 1) * vel * 0.05


def ching(open_: bool = True, vel: float = 1.0, seed: int = 0) -> np.ndarray:
    """Thai finger cymbals: open 'ching' rings, closed 'chap' is damped."""
    dur = 1.2 if open_ else 0.12
    n = int(dur * SR)
    t = np.arange(n) / SR
    rng = np.random.default_rng(seed)
    metal = sum(np.sin(2 * np.pi * f * t) for f in (3150, 4420, 5980, 7210))
    noise = highpass(rng.standard_normal(n), 6000)
    dec = 0.45 if open_ else 0.03
    return (metal * 0.12 + noise * 0.08) * env_perc(n, 0.0008, dec) * vel


def thon(vel: float = 1.0, low: bool = True) -> np.ndarray:
    """Soft hand drum: pitch-dropping sine thump."""
    n = int(0.35 * SR)
    t = np.arange(n) / SR
    f0 = 95 if low else 180
    freq = f0 * (1 + 0.6 * np.exp(-t / 0.03))
    phase = 2 * np.pi * np.cumsum(freq) / SR
    return np.sin(phase) * env_perc(n, 0.002, 0.11 if low else 0.07) * vel * 0.5


def sparkle_note(freq: float, vel: float = 1.0) -> np.ndarray:
    n = int(0.9 * SR)
    t = np.arange(n) / SR
    return (np.sin(2 * np.pi * freq * t) + 0.3 * np.sin(2 * np.pi * freq * 4.2 * t)) * env_perc(n, 0.002, 0.25) * vel * 0.3


# ───────────────────────── composition ─────────────────────────

PENTA = [0, 2, 4, 7, 9]  # do re mi sol la


def scale_note(root: int, degree: int) -> int:
    octave, idx = divmod(degree, 5)
    return root + 12 * octave + PENTA[idx]


def make_melody(rng: np.random.Generator, bars: int, steps_per_bar: int, rest_prob: float) -> list[int | None]:
    """Phrase-shaped pentatonic line: A A' B A'' (4 phrases), mostly stepwise, ends on the tonic."""
    phrase_bars = bars // 4

    def phrase(start: int, end: int) -> list[int | None]:
        n = phrase_bars * steps_per_bar
        line: list[int | None] = []
        d = start
        for i in range(n):
            if i == n - 1:
                d = end
            elif rng.random() < 0.75:
                d += int(rng.choice([-1, 1, 1, -1, 2, -2]))
            else:
                d += int(rng.choice([-3, 3]))
            d = int(np.clip(d, 0, 9))
            rest = rng.random() < rest_prob and i % 2 == 1 and i != n - 1
            line.append(None if rest else d)
        return line

    a = phrase(4, 2)
    a2 = a[:-steps_per_bar] + phrase(3, 0)[-steps_per_bar:]
    b = phrase(6, 4)
    a3 = a[:-steps_per_bar] + phrase(2, 0)[-steps_per_bar:]
    return a + a2 + b + a3


def place(track: np.ndarray, sound: np.ndarray, at: float, pan: float = 0.0) -> None:
    i = int(at * SR)
    if i >= track.shape[0]:
        return
    j = min(track.shape[0], i + len(sound))
    left = np.cos((pan + 1) * np.pi / 4)
    right = np.sin((pan + 1) * np.pi / 4)
    track[i:j, 0] += sound[: j - i] * left
    track[i:j, 1] += sound[: j - i] * right


def compose(name: str, *, bpm: float, bars: int, root: int, seed: int, style: str) -> np.ndarray:
    rng = np.random.default_rng(seed)
    beat = 60 / bpm
    bar = beat * 4
    length = bars * bar
    tail = 3.0
    track = np.zeros((int((length + tail) * SR), 2))

    steps = 8 if style in ("theme", "day") else 4
    step = bar / steps
    melody = make_melody(rng, bars, steps, rest_prob=0.25 if style in ("theme", "day") else 0.45)
    # chord roots per bar (scale degrees): I – V – vi – I feel, pentatonic friendly
    progression = [0, 0, 3, 3, 4, 4, 3, 0]

    for i, d in enumerate(melody):
        if d is None:
            continue
        at = i * step
        note = scale_note(root, d)
        swing = 0.0 if i % 2 == 0 else step * 0.06
        if style in ("theme", "day"):
            place(track, ranat(midi(note), vel=0.55 if i % 2 else 0.7, seed=i), at + swing, pan=-0.2)
            if i % 4 == 0:  # Thai-style octave doubling on strong steps
                place(track, ranat(midi(note + 12), vel=0.25, seed=i + 99), at + swing, pan=0.3)
        elif style == "evening":
            place(track, khim(midi(note), vel=0.5, seed=i), at, pan=-0.15)
        elif style == "night":
            place(track, khong(midi(note + 12), dur=2.4, vel=0.32), at, pan=0.1)
        elif style == "magic":
            place(track, sparkle_note(midi(note + 12), vel=0.8), at, pan=float(np.sin(i)) * 0.6)

    for b in range(bars):
        at = b * bar
        deg = progression[b % len(progression)]
        chord_root = scale_note(root - 12, deg)
        place(track, pad([midi(chord_root), midi(chord_root + 7), midi(chord_root + 16)], bar + 0.6, vel=0.9 if style != "theme" else 0.6), at)
        if style in ("theme", "day", "evening"):
            place(track, bass(midi(chord_root - 12), vel=0.7), at)
            place(track, bass(midi(chord_root - 5), vel=0.45), at + 2 * beat)
        if style == "night":
            place(track, khong(midi(chord_root), dur=3.0, vel=0.25), at, pan=-0.3)
        if style in ("theme", "day"):
            # khong wong answer on beat 4
            place(track, khong(midi(scale_note(root, (b * 2) % 5 + 5)), dur=1.6, vel=0.18), at + 3 * beat + beat / 2, pan=0.4)

        for k in range(4):
            beat_at = at + k * beat
            if style in ("theme", "day"):
                place(track, ching(open_=(k % 2 == 1), vel=0.5, seed=b * 4 + k), beat_at, pan=0.5)
                if k in (0, 2):
                    place(track, thon(vel=0.55 if k == 0 else 0.35), beat_at)
                if k == 3:
                    place(track, thon(vel=0.25, low=False), beat_at + beat / 2)
            elif style == "evening":
                if k == 1:
                    place(track, ching(open_=True, vel=0.28, seed=b), beat_at, pan=0.5)
                if k == 0:
                    place(track, thon(vel=0.3), beat_at)
            elif style == "magic":
                if k == 0 and b % 2 == 0:
                    place(track, ching(open_=True, vel=0.2, seed=b), beat_at, pan=0.4)

    if style == "magic":
        # slow shimmering arpeggio layer
        for i in range(int(length / (beat / 2))):
            note = scale_note(root + 12, (i * 2) % 10)
            place(track, sparkle_note(midi(note), vel=0.25), i * beat / 2, pan=float(np.cos(i * 0.7)) * 0.7)

    # space
    for ch in range(2):
        track[:, ch] = reverb(track[:, ch], seconds=2.2 if style in ("night", "magic") else 1.4,
                              mix=0.32 if style in ("night", "magic") else 0.2, seed=ch + 1)

    # seamless loop: fold the tail back onto the start
    n_loop = int(length * SR)
    looped = track[:n_loop].copy()
    tail_part = track[n_loop:]
    looped[: len(tail_part)] += tail_part
    return master(looped, target_rms=0.09)


def master(x: np.ndarray, target_rms: float) -> np.ndarray:
    x = x - np.mean(x, axis=0)
    x = np.stack([highpass(x[:, c], 60) for c in range(x.shape[1])], axis=1)
    rms = np.sqrt(np.mean(x**2))
    if rms > 0:
        x *= target_rms / rms
    # gentle soft clip
    return np.tanh(x * 1.2) / 1.2


# ───────────────────────── sound effects ─────────────────────────

def sfx_whoosh() -> np.ndarray:
    n = int(1.1 * SR)
    t = np.arange(n) / SR
    rng = np.random.default_rng(7)
    noise = rng.standard_normal(n)
    out = np.zeros(n)
    # sweep a band-pass upward in chunks
    chunks = 40
    for c in range(chunks):
        a, b = c * n // chunks, (c + 1) * n // chunks
        centre = 300 + 3500 * (c / chunks) ** 1.5
        seg = bandpass(noise[max(0, a - 2000): b], centre * 0.6, min(centre * 1.6, 18000))[-(b - a):]
        out[a:b] = seg
    shape = np.sin(np.pi * np.clip(t / 1.1, 0, 1)) ** 2
    return master(np.stack([out * shape, np.roll(out, 300) * shape], axis=1), 0.12)


def sfx_sparkle() -> np.ndarray:
    track = np.zeros((int(1.8 * SR), 2))
    for i, d in enumerate([0, 2, 4, 5, 7, 9, 10]):
        place(track, sparkle_note(midi(scale_note(84, d)), vel=0.9), i * 0.07, pan=-0.6 + i * 0.2)
    for ch in range(2):
        track[:, ch] = reverb(track[:, ch], 1.4, 0.35, ch + 3)
    return master(track, 0.08)


def sfx_pop() -> np.ndarray:
    n = int(0.25 * SR)
    t = np.arange(n) / SR
    freq = 420 + 900 * (1 - np.exp(-t / 0.04))
    s = np.sin(2 * np.pi * np.cumsum(freq) / SR) * env_perc(n, 0.002, 0.05)
    return master(np.stack([s, s], axis=1), 0.12)


def sfx_chime() -> np.ndarray:
    track = np.zeros((int(3.0 * SR), 2))
    for i, d in enumerate([0, 4, 7, 9, 12]):
        place(track, khong(midi(scale_note(72, d % 10) + (12 if d >= 10 else 0)), 2.4, 0.6), i * 0.12, pan=-0.4 + i * 0.2)
    for ch in range(2):
        track[:, ch] = reverb(track[:, ch], 2.0, 0.35, ch + 5)
    return master(track, 0.09)


# ───────────────────────── output ─────────────────────────

def write_mp3(path: str, audio: np.ndarray, bitrate: str = "160k") -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    audio = np.clip(audio, -1, 1)
    with tempfile.NamedTemporaryFile(suffix=".wav", delete=False) as tmp:
        wavfile.write(tmp.name, SR, (audio * 32767).astype(np.int16))
        subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-i", tmp.name, "-b:a", bitrate, path], check=True)
    os.unlink(tmp.name)
    print(f"  + {os.path.relpath(path, ROOT)}  {len(audio) / SR:.1f}s")


TRACKS = {
    # name: tempo, bars (multiple of 4), root note, seed, style
    "theme": dict(bpm=104, bars=16, root=67, seed=11, style="theme"),    # bright opening / closing
    "day": dict(bpm=96, bars=16, root=65, seed=23, style="day"),         # forest by day
    "evening": dict(bpm=80, bars=16, root=62, seed=5, style="evening"),  # sunset, gentle
    "magic": dict(bpm=70, bars=12, root=64, seed=31, style="magic"),     # campfire, Phra In
    "night": dict(bpm=62, bars=12, root=60, seed=42, style="night"),     # moon lullaby
}


def main() -> None:
    print("Music")
    for name, cfg in TRACKS.items():
        write_mp3(os.path.join(ROOT, "public", "music", f"{name}.mp3"), compose(name, **cfg))
    print("Sound effects")
    write_mp3(os.path.join(ROOT, "public", "sfx", "whoosh.mp3"), sfx_whoosh(), "128k")
    write_mp3(os.path.join(ROOT, "public", "sfx", "sparkle.mp3"), sfx_sparkle(), "128k")
    write_mp3(os.path.join(ROOT, "public", "sfx", "pop.mp3"), sfx_pop(), "128k")
    write_mp3(os.path.join(ROOT, "public", "sfx", "chime.mp3"), sfx_chime(), "128k")


if __name__ == "__main__":
    main()
